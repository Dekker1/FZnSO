// The shared API IR → Starlight MDX.
//
// One renderer for all four surfaces, so a Rust struct, a C++ class and a
// Python class read the same way. Pages are real content: site theme, site
// search, site table of contents, and anchors the specification can link to.

import { mkdir, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { attr, mdx } from '../mdx.mjs';

/**
 * `###` heading anchors, matching what Starlight's slugger produces.
 *
 * The underscore has to survive: github-slugger treats it as a word character,
 * so `fznso_export` anchors as `fznso_export`. Folding it to `-` here produced
 * links to `#fznso-export`, which is nothing.
 */
export const anchorOf = (name) =>
	name
		.toLowerCase()
		.replace(/::/g, '')
		.replace(/[^a-z0-9_]+/g, '-')
		.replace(/^-|-$/g, '');

/** A member's anchor, stable and readable: `#fznsomodelmethods-layer_unchanged`. */
export const memberAnchorOf = (owner, member) => `${anchorOf(owner)}-${member}`;

/**
 * Turn `[`Foo::bar`]` doc links into real links.
 *
 * rustdoc emits them for its own renderer and Doxygen leaves them as written;
 * either way they are cross-references, and resolving them against the symbol
 * index is what stops the reference reading like three separate documents.
 * Anything unresolved keeps its code formatting and loses only the brackets.
 */
function resolveLinks(text, symbols) {
	return String(text).replace(/\[`([^`\]]+)`\]/g, (_, target) => {
		const key = target
			.replace(/^(?:crate|Self|self)::/, '')
			.replace(/<[^>]*>/g, '')
			.replace(/\(\)$/, '');
		const url = symbols.get(key) ?? symbols.get(key.split(/::|\./).pop());
		return url ? `[\`${target}\`](${url})` : `\`${target}\``;
	});
}

/** Everything a filter query should match for one item. */
const searchKey = (item) =>
	[item.kind, item.name, item.name.replace(/[_:.]+/g, ' '), item.signature, item.docs]
		.join(' ')
		.toLowerCase()
		.slice(0, 600);

/**
 * A `<Signature>` call.
 *
 * The text goes through `JSON.stringify` into a JSX expression rather than
 * being written as markdown: signatures carry quotes, angle brackets and
 * underscores, all of which the markdown pipeline would rewrite into something
 * that is no longer the declaration.
 */
const signature = (text, { kind, source, member } = {}) =>
	`<Signature text={${JSON.stringify(text)}}` +
	`${kind ? ` kind="${kind}"` : ''}` +
	`${source ? ` source="${source}"` : ''}` +
	`${member ? ' member' : ''} />`;

function renderMember(owner, member, symbols) {
	const id = memberAnchorOf(owner.name, member.name);
	const docs = member.docs ? `\n${mdx(resolveLinks(member.docs.trim(), symbols))}\n` : '';
	const nested = (member.members ?? [])
		.map((v) => signature(v.signature, { member: true }) + (v.docs ? `\n\n${mdx(v.docs.trim())}\n` : ''))
		.join('\n');

	return `
<div class="api-member" id="${id}">

${signature(member.signature, { kind: member.kind, member: true })}
${docs}${nested ? `\n${nested}\n` : ''}
</div>
`;
}

function renderItem(item, symbols) {
	const docs = item.docs ? `\n${mdx(resolveLinks(item.docs.trim(), symbols))}\n` : '';
	const members = (item.members ?? []).map((m) => renderMember(item, m, symbols)).join('');

	return `
<div class="filter-entry" data-search="${attr(searchKey(item))}">

### ${mdx(item.name)}

${signature(item.signature, { source: item.source })}
${docs}${members ? `\n<div class="api-members">\n${members}\n</div>\n` : ''}
</div>
`;
}

/**
 * Index every symbol on a page so cross-references can resolve to it.
 *
 * Both the bare name and the qualified one are registered, because a doc
 * comment may write either.
 */
export function indexSymbols(page, symbols) {
	for (const group of page.groups) {
		for (const item of group.items) {
			const url = `/reference/${page.slug}/#${anchorOf(item.name)}`;
			symbols.set(item.name, url);
			const short = item.name.split('::').pop();
			if (!symbols.has(short)) symbols.set(short, url);
			for (const member of item.members ?? []) {
				const memberUrl = `/reference/${page.slug}/#${memberAnchorOf(item.name, member.name)}`;
				symbols.set(`${item.name}::${member.name}`, memberUrl);
				symbols.set(`${short}::${member.name}`, memberUrl);
				symbols.set(`${short}.${member.name}`, memberUrl);
			}
		}
	}
}

export async function renderPage(page, symbols, outDir) {
	const total = page.groups.reduce((n, g) => n + g.items.length, 0);
	const body = page.groups
		.map(
			(group) =>
				`\n## ${group.label}\n\n${group.items.map((i) => renderItem(i, symbols)).join('\n')}`,
		)
		.join('\n');

	// Quoted: a description like "The fznso crate: both sides…" is not valid
	// YAML unquoted, and JSON string escaping is a subset of YAML's.
	const mdxPage = `---
# Generated by docs/scripts/api/ — do not edit.
title: ${JSON.stringify(page.title)}
description: ${JSON.stringify(page.description)}
${page.order ? `sidebar:\n  order: ${page.order}\n` : ''}---

import FilterBox from '../../../components/FilterBox.astro';
import Signature from '../../../components/Signature.astro';

${page.intro.trim()}

<FilterBox count={${total}} noun="${page.noun}" />

<div class="filter-list">
${body}
</div>
`;

	await mkdir(outDir, { recursive: true });
	await writeFile(join(outDir, `${page.slug}.mdx`), mdxPage);
	return total;
}
